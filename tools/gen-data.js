// Writes WarlockSim/Data.lua from the DPS sim's own data files, so no number is ever copied by hand.
//   node tools/gen-data.js            (sim folder: ../wow-forever-warlock-sim, or the SIM_DIR environment variable)
// Run it after every change of the sim's data/ files, then tools/check-engine.js.
const fs = require('fs'), path = require('path'), vm = require('vm'), cp = require('child_process');
const ROOT = path.join(__dirname, '..');
const SIM = process.env.SIM_DIR || path.join(ROOT, '..', 'wow-forever-warlock-sim');
const WL = require(path.join(SIM, 'tools', 'load-wl.js')).load(SIM, ['engine/settings-code.js']);   // + the retired settings

// ---- Lua writer: keeps the key order of the JS objects (and writes it out where the engine depends on it) ----
const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
const RESERVED = new Set(['and', 'break', 'do', 'else', 'elseif', 'end', 'false', 'for', 'function', 'if', 'in', 'local', 'nil', 'not', 'or', 'repeat', 'return', 'then', 'true', 'until', 'while']);
function str(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '')
    .replace(/[\u0080-￿]/g, c => Array.from(Buffer.from(c, 'utf8')).map(b => '\\' + b).join('')) + '"';
}
function num(n) {
  if (!isFinite(n)) throw new Error('not a finite number: ' + n);
  return String(n);
}
function lua(v, ind, drop) {
  ind = ind || '';
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return num(v);
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return str(v);
  if (Array.isArray(v)) return '{ ' + v.map(x => lua(x, ind, drop)).join(', ') + (v.length ? ' ' : '') + '}';
  const keys = Object.keys(v).filter(k => v[k] !== null && v[k] !== undefined && typeof v[k] !== 'function' && !(drop && drop.has(k)));
  if (!keys.length) return '{}';
  const flat = keys.every(k => typeof v[k] !== 'object' || Array.isArray(v[k]) && v[k].every(x => typeof x !== 'object'));
  const kv = k => (IDENT.test(k) && !RESERVED.has(k) ? k : '[' + str(k) + ']') + ' = ' + lua(v[k], ind + '  ', drop);
  if (flat) return '{ ' + keys.map(kv).join(', ') + ' }';
  return '{\n' + keys.map(k => ind + '  ' + kv(k) + ',\n').join('') + ind + '}';
}
const order = o => lua(Object.keys(o));

// ---- talent ids of the game client (trait node, definition, rank spell) from the archived talent data ----
const rawFile = path.join(SIM, 'research', 'raw', 'wowhead_forever_talents-classic_dv27.js');
const nodes = {};
if (fs.existsSync(rawFile)) {
  const ctx = { RAW: {} };
  ctx.WH = { setPageData: (k, v) => { ctx.RAW.talentCalc = v; }, Gatherer: { addData: () => {} } };
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(rawFile, 'utf8'), ctx);
  const t = ctx.RAW.talentCalc.talents;
  Object.keys(t).forEach(tree => Object.keys(t[tree]).forEach(id => { nodes[id] = t[tree][id]; }));
} else console.warn('NOTE: ' + rawFile + ' not found - talents are written without their spell ids');

const talents = WL.TALENTS.map(t => {
  const o = {}, n = nodes[t.wid];
  Object.keys(t).forEach(k => { o[k] = t[k]; });
  if (n) { o.spell = n.ranks[0]; o.def = n.definition; }
  return o;
});

// ---- priority actions: everything but the pick function (those are written by hand in Engine.lua) ----
const actions = Object.keys(WL.ACTIONS).map(k => {
  const a = WL.ACTIONS[k], o = { key: k, label: a.label };
  if (a.filler) o.filler = true;
  if (a.preFiller) o.preFiller = true;
  if (a.params) o.params = a.params;
  return o;
});

let commit = 'unknown', dirty = false;
try {
  commit = cp.execSync('git -C "' + SIM + '" rev-parse --short HEAD').toString().trim();
  dirty = cp.execSync('git -C "' + SIM + '" status --short -- data engine').toString().trim().length > 0;
} catch (e) { /* no git */ }
if (dirty) console.warn('NOTE: the sim folder has uncommitted changes in data/ or engine/ - they are in this copy');

const book = WL.spellsFor({ options: { bookRanks: true } });
const NO_TEXT = new Set(['text', 'icon']);
const out = [];
out.push('-- GENERATED by tools/gen-data.js from the DPS sim\'s data files. Do not edit: change the sim, then run the script again.');
out.push('local ADDON, WL = ...');
out.push('WL.SIM_COMMIT = ' + str(commit + (dirty ? '+' : '')));
out.push('WL.WARLOCK_BASE_60 = ' + lua(WL.WARLOCK_BASE_60));
out.push('WL.SPELLS = ' + lua(WL.SPELLS));
out.push('WL.SPELL_ORDER = ' + order(WL.SPELLS));
out.push('WL.BOOK_SPELLS = ' + lua(Object.keys(WL.BOOK_RANKS).reduce((o, k) => { o[k] = book[k]; return o; }, {})));
out.push('WL.PANDEMIC_SPELLS = ' + lua(WL.PANDEMIC_SPELLS));
out.push('WL.NIGHTFALL_SPELLS = ' + lua(WL.NIGHTFALL_SPELLS));
out.push('WL.SOUL_SIPHON_EFFECTS = ' + lua(WL.SOUL_SIPHON_EFFECTS));
out.push('WL.OILS = ' + lua(WL.OILS));
out.push('WL.TREES = ' + lua(WL.TREES));
out.push('WL.TREE_ORDER = ' + order(WL.TREES));
out.push('WL.TALENTS = ' + lua(talents));
out.push('WL.RACES = ' + lua(WL.RACES));
out.push('WL.RACE_KEYS = ' + lua(WL.RACE_KEYS));
out.push('WL.BASELINE_RACE = ' + str(WL.BASELINE_RACE));
out.push('WL.BUILDS = ' + lua(WL.BUILDS));
// trinket and weapon enchant effects, keyed by the game's item id / enchant id (numbers in Lua too)
const byId = o => '{\n' + Object.keys(o || {}).map(k => '  [' + num(+k) + '] = ' + lua(o[k], '  ') + ',\n').join('') + '}';
out.push('WL.TRINKET_FX = ' + byId(WL.TRINKET_FX));
out.push('WL.ENCHANT_FX = ' + byId(WL.ENCHANT_FX));
out.push('WL.ACTION_META = ' + lua(actions));
out.push('WL.CONFLAG_EXPIRE_S = ' + num(WL.CONFLAG_EXPIRE_S));
out.push('WL.DOT_ACTIONS = ' + lua(WL.DOT_ACTIONS));
out.push('WL.TIMELINE_SPELLS = ' + lua(WL.TIMELINE_SPELLS));
out.push('WL.PET_KEYS = ' + lua(WL.PET_KEYS));
out.push('WL.SACRIFICE_KEYS = ' + lua(WL.SACRIFICE_KEYS));
out.push('WL.STAT_WEIGHT_KEYS = ' + lua(WL.STAT_WEIGHT_KEYS));
out.push('WL.RETIRED_SETTINGS = ' + lua(WL.RETIRED_SETTINGS));
out.push('WL.RETIRED_TALENTS = ' + lua(WL.RETIRED_TALENTS));
out.push('WL.DEFAULT_CONFIG = ' + lua(WL.DEFAULT_CONFIG, '', NO_TEXT));
out.push('WL.BUFF_ORDER = ' + order(WL.DEFAULT_CONFIG.buffs));
out.push('WL.DEBUFF_ORDER = ' + order(WL.DEFAULT_CONFIG.debuffs));
out.push('WL.CONSUMABLE_ORDER = ' + order(WL.DEFAULT_CONFIG.consumables));
out.push('WL.PROFESSION_ORDER = ' + order(WL.DEFAULT_CONFIG.professions));
out.push('');
fs.mkdirSync(path.join(ROOT, 'WarlockSim'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'WarlockSim', 'Data.lua'), out.join('\n'));
console.log('WarlockSim/Data.lua written from sim commit ' + commit + (dirty ? ' (+ uncommitted changes)' : '') + ': ' +
  Object.keys(WL.SPELLS).length + ' spells, ' + talents.length + ' talents (' + talents.filter(t => t.spell).length + ' with ids), ' +
  WL.BUILDS.length + ' builds, ' + actions.length + ' priority actions');

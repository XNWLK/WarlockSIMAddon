// Writes WarlockSim/Expected.lua: the exact total damage of a few fights, played by the DPS sim's own engine.
// The addon's "/wsim test" plays the same fights inside the game and compares - that proves the game's Lua gives the
// same numbers as the sim. Run after tools/gen-data.js (every time the sim's data or engine changed).
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const SIM = process.env.SIM_DIR || path.join(ROOT, '..', 'wow-forever-warlock-sim');
const WL = require(path.join(SIM, 'tools', 'load-wl.js')).load(SIM);
const { toLua } = require('./lua-ser.js');
const races = WL.RACE_KEYS, fights = [];
WL.BUILDS.forEach((b, bi) => {
  [0, 1].forEach(i => {
    const race = races[(bi + i * 2) % races.length], fp = WL.fightParams(WL.DEFAULT_CONFIG, i);
    const r = WL.simulateOnce(b, race, WL.DEFAULT_CONFIG, { seed: fp.seed, duration: fp.duration, log: false });
    fights.push({ build: b.key, race, i, total: r.total });
  });
});
fs.writeFileSync(path.join(ROOT, 'WarlockSim', 'Expected.lua'),
  '-- GENERATED by tools/gen-expected.js. Total damage of ' + fights.length + ' fights as the DPS sim plays them (default settings).\n' +
  'local ADDON, WL = ...\nWL.EXPECTED = { fights = {\n' + fights.map(f => '  ' + toLua(f) + ',\n').join('') + '} }\n');
console.log('WarlockSim/Expected.lua written: ' + fights.length + ' fights');
